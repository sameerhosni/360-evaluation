type Dict = typeof DICT["en"];
type DotPath<T, P extends string = ""> = {
  [K in keyof T & string]: T[K] extends object
    ? T[K] extends readonly string[]
      ? `${P}${K}`
      : DotPath<T[K], `${P}${K}.`> | `${P}${K}`
    : `${P}${K}`;
}[keyof T & string];

export type DictKey = DotPath<Dict>;

export function t(locale: Locale, key: DictKey | string): string {
  const path = (key as string).split(".");
  let node: unknown = DICT[locale];
  for (const seg of path) {
    if (node && typeof node === "object" && seg in (node as Record<string, unknown>)) {
      node = (node as Record<string, unknown>)[seg];
    } else {
      node = path.reduce<unknown>((acc, s) => {
        if (acc && typeof acc === "object" && s in (acc as Record<string, unknown>)) {
          return (acc as Record<string, unknown>)[s];
        }
        return undefined;
      }, DICT.en);
      break;
    }
  }
  return typeof node === "string" ? node : (key as string);
}

/** Looks up a non-string node (e.g. an array of strings) from the dictionary. */
export function tNode(locale: Locale, key: string): unknown {
  const path = key.split(".");
  let node: unknown = DICT[locale];
  for (const seg of path) {
    if (node && typeof node === "object" && seg in (node as Record<string, unknown>)) {
      node = (node as Record<string, unknown>)[seg];
    } else {
      return undefined;
    }
  }
  return node;
}

/** Substitute {placeholders} in a template string. */
export function tFormat(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
